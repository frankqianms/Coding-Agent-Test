public class Data {
    // Private fields with comments
    private String name;
    private int value;
    
    /**
     * Constructor for Data class
     * @param name The name field
     * @param value The value field
     */
    public Data(String name, int value) {
        this.name = name;
        this.value = value;
    }
    
    // Getter methods
    public String getName() {
        return name;
    }
    
    public int getValue() {
        return value;
    }
}
